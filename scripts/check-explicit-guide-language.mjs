import fs from 'node:fs';
import assert from 'node:assert/strict';
const js=fs.readFileSync('site/assets/site.js','utf8');
const failures=[];
const check=(ok,message)=>{if(!ok)failures.push(message)};
const start=js.indexOf('function ensureGuideLanguageField(form)');
const end=js.indexOf('function updateGuideLanguageField(product)',start);
check(start>=0&&end>start,'guide language implementation missing');
const block=start>=0&&end>start?js.slice(start,end):'';
check(block.includes('name="guide_language" required aria-required="true"'),'guiding language not required');
check(block.includes('aria-describedby="booking-guide-language-help"'),'missing screen-reader help association');
check(block.includes('select.disabled=!languages.length;'),'missing fail-closed no-languages state');
check(block.includes("select.value=before&&languages.includes(before)?before:'';"),'missing guest-selected-language-only preservation');
check(!block.includes('smartDefault'),'must not auto-select English, site locale or first item');
check(block.includes("const before=preserve?String(select.value||''):'';"),'selection preservation contract changed');
check(block.includes('form._updateGuideLanguages(null,{preserve:false})'),'language must initialize unselected');
check(js.includes("if(!allowedGuideLanguages.includes(guideLanguage))"),'selected guide language no longer checked against catalog');
check(js.includes("guide_language:guideLanguage})"),'held language no longer passed to FBM hold');
check(js.includes("guide_language:submission.guide_language"),'booking language no longer submitted to FBM');
check(js.includes('Guide languages cannot be verified right now.'),'disabled-language error explanation missing');
check(block.includes('Nem választunk ki nyelvet automatikusan.'),'Hungarian explicit-choice copy missing');
check(block.includes('לא נבחרת שפה באופן אוטומטי.'),'Hebrew explicit-choice copy missing');
check(block.includes('We do not select a language automatically.'),'English explicit-choice copy missing');
const noSelection=before=>{const available=['en','hu'];return before&&available.includes(before)?before:''};
assert.equal(noSelection(''),'');
assert.equal(noSelection('hu'),'hu');
assert.equal(noSelection('fr'),'');
if(failures.length){console.error('Explicit language selection guard FAILED:\n'+failures.join('\n'));process.exit(1)}
console.log('Guide-language user choice, fail-closed behavior, accessibility and FBM request contract OK.');
